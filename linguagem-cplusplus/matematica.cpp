#include <iostream>
#include <cmath>

using namespace std;

int main(){
    cout << sqrt(900.0) << endl; /* Raiz quadrada */
    cout << ceil(9.2) << endl; /* Arredonda um número  */
    cout << exp(1.0) << endl; /* Função exponencia e^x*/
    cout << log10(100) << endl; /* Log de x na base 10 */
    return 0;
}